text = "Я с детства хотел завести собаку, но родители мне не разрешали. Пока я был ребёнком, у меня жил хомяк Хома. Хома был очень маленький и пушистый. Его шерсть была средней длинны и коричневого цвета. Родители купили большую клетку для него, с двумя этажами. Я был очень рад, когда у меня появился маленький друг. Было очень весело смотреть как Хома бегает в колесе. Мне нравилось кормить его морковкой и орехами. Когда я вырос, и начал жить отдельно, я завел собаку. Я всегда мечтал о большой собаке, с которой я смогу гулять и играть в парке. Теперь она у меня есть. Это большой и дружелюбный лабрадор. Я назвал его Джек. Мы с Джеком гуляем два раза в день. Он сделал мою жизнь более активной. С самого начала я обучаю его разным командам. Он уже умеет сидеть, лежать и прыгать. Мне нравится смотреть на Джека в солнечную погоду. Его золотая шерсть выглядит прекрасно на солнце. Джек это мой самый верный и лучший друг."

def generate_key():
    alph_list = list(rus_alp)
    random.shuffle(alph_list)
    key = "".join(alph_list)
    return key

def encrypt(text, key):
    # Создаем словарь замены
    zamena = {}
    for i, letter in enumerate(rus_alp):
        zamena[letter] = key[i]
    
    encrypt = []
    for char in text.lower():
        if char in zamena:
            encrypt.append(zamena[char])
        else:
            # Оставляем пробелы и знаки препинания как есть
            encrypt.append(char)
    
    return "".join(encrypt)

# Генерируем ключ и шифруем
key = generate_key()
encrypted_text = encrypt(text, key)

